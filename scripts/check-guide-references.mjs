#!/usr/bin/env node
/**
 * Contributor guide reference check (CI guard).
 *
 * Fails when a contributor guide (any `AGENTS.md`, or a `docs/*.md` file)
 * points at an in-repo file that does not exist, so stale pointers cannot
 * come back after a guide is split or moved. Only existence is checked,
 * never headings.
 *
 * Two kinds of pointer are read:
 *   - markdown links `[text](relative/path)`, resolved relative to the guide;
 *   - backticked paths that start with `./` or `../`, or that are repo-root
 *     paths ending in `.md`. The guides write `../<repo>/...` relative to the
 *     repo root, so a backticked path passes when it exists relative to the
 *     guide OR relative to the repo root.
 * `#anchors` are stripped; http(s)/mailto links and anchor-only links are
 * skipped. Fenced code blocks are ignored.
 *
 * Sibling checkouts: a path that leaves this repo (`../turbopaneld/...`,
 * `../ui/...`, `../dev/...`, ...) is skipped when that sibling checkout is
 * absent (CI has only this repo) and checked when it is present.
 *
 * Known false positives go in ALLOWLIST below, one entry per pointer with a
 * reason.
 *
 * Usage:
 *   node scripts/check-guide-references.mjs
 *   pnpm check:guide-references
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

// { file: repo-relative guide, target: pointer text as written, reason }
export const ALLOWLIST = [
  {
    file: 'docs/host-layout.md',
    target: '../ui/dist',
    reason: 'build output of the ui checkout, only exists after a build',
  },
  {
    file: 'docs/host-layout.md',
    target: './certs/self-signed.crt',
    reason: 'generated by the development setup, not committed',
  },
  {
    file: 'docs/host-layout.md',
    target: './certs/self-signed.key',
    reason: 'generated by the development setup, not committed',
  },
  {
    file: 'docs/setup.md',
    target: './console',
    reason: 'command run from the dev checkout, not a file of this repo',
  },
  {
    file: 'src/db/AGENTS.md',
    target: './scripts/introspect.sh',
    reason: 'command run from the dev checkout, not a file of this repo',
  },
  {
    file: 'src/db/AGENTS.md',
    target: './scripts/sync.sh',
    reason: 'command run from the dev checkout, not a file of this repo',
  },
  {
    file: 'src/db/AGENTS.md',
    target: '../../drizzle/',
    reason: 'scratch directory that is created and deleted during introspection, never committed',
  },
  {
    file: 'src/features/compose/AGENTS.md',
    target: './data',
    reason: 'example bind path inside a service directory on a host, not a repo file',
  },
]

const SKIP_DIRS = new Set(['node_modules', 'coverage', 'dist', 'build', 'vendor'])
const KEEP_DOT_DIRS = new Set(['.github', '.githooks'])

/** Replace fenced code blocks with blank lines so line numbers stay true. */
export function stripFences(text) {
  let inFence = false
  return text
    .split('\n')
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) {
        inFence = !inFence
        return ''
      }
      return inFence ? '' : line
    })
    .join('\n')
}

function looksLikeBacktickedPath(token) {
  if (token.includes('...') || /[\s<>*{}|…$():]/.test(token)) return false
  const bare = token.replace(/[#?].*$/, '')
  if (bare.startsWith('./') || bare.startsWith('../')) return true
  return bare.includes('/') && bare.endsWith('.md') && !bare.startsWith('/')
}

/** Pull link and backticked-path pointers out of one guide's text. */
export function extractReferences(text) {
  const refs = []
  stripFences(text)
    .split('\n')
    .forEach((line, i) => {
      for (const m of line.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
        refs.push({ kind: 'link', target: m[1], line: i + 1 })
      }
      for (const m of line.matchAll(/`([^`]+)`/g)) {
        if (looksLikeBacktickedPath(m[1])) refs.push({ kind: 'code', target: m[1], line: i + 1 })
      }
    })
  return refs
}

/**
 * Decide one pointer. `file` is the guide's repo-relative path; `exists`
 * is injected so the resolver stays pure. Status is one of: ok, missing,
 * skipped-external, skipped-anchor, skipped-sibling, allowlisted.
 */
export function resolveReference({ kind, target, file, repoRoot, exists, allowlist = ALLOWLIST }) {
  if (allowlist.some((a) => a.file === file && a.target === target))
    return { status: 'allowlisted' }
  if (/^[a-z][a-z0-9+.-]*:/i.test(target)) return { status: 'skipped-external' }
  const bare = target.replace(/[#?].*$/, '')
  if (bare === '') return { status: 'skipped-anchor' }

  const candidates = [path.resolve(repoRoot, path.dirname(file), bare)]
  if (kind === 'code' || bare.startsWith('/')) {
    candidates.push(path.resolve(repoRoot, bare.replace(/^\/+/, '')))
  }
  if (candidates.some((c) => exists(c))) return { status: 'ok' }

  const siblingAbsent = candidates.some((c) => {
    const rel = path.relative(repoRoot, c).split(path.sep)
    return (
      rel[0] === '..' && rel[1] && rel[1] !== '..' && !exists(path.resolve(repoRoot, '..', rel[1]))
    )
  })
  return { status: siblingAbsent ? 'skipped-sibling' : 'missing' }
}

function collectGuides(dir = ROOT, rel = '') {
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const childRel = rel ? `${rel}/${entry.name}` : entry.name
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue
      if (entry.name.startsWith('.') && !KEEP_DOT_DIRS.has(entry.name)) continue
      out.push(...collectGuides(path.join(dir, entry.name), childRel))
    } else if (entry.name === 'AGENTS.md' || (rel === 'docs' && entry.name.endsWith('.md'))) {
      out.push(childRel)
    }
  }
  return out
}

function main() {
  const problems = []
  for (const file of collectGuides()) {
    const text = fs.readFileSync(path.join(ROOT, file), 'utf8')
    for (const ref of extractReferences(text)) {
      const { status } = resolveReference({ ...ref, file, repoRoot: ROOT, exists: fs.existsSync })
      if (status === 'missing') problems.push(`${file}:${ref.line}: ${ref.target}`)
    }
  }
  if (problems.length > 0) {
    console.error('Contributor guides point at files that do not exist:')
    for (const p of problems) console.error(`  ${p}`)
    console.error(
      'Fix the pointer, or add a reasoned entry to ALLOWLIST in scripts/check-guide-references.mjs.'
    )
    process.exit(1)
  }
  console.log('Contributor guide references: ok')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
